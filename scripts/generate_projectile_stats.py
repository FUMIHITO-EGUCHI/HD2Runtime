"""Generate domains/projectile_stats.lua: the read-only vanilla stats of every projectile a catalogued attack output
fires, for hd2.attack_output(id):stats() (0.31.2; docs/attack-outputs.md "Stats of an output's projectile").

From research/projectile-stats-F5FEE03DCFDB.json (scripts/research_projectile_stats.py: the pinned datalibrary rows,
checked against research/projectile-components and the explosion catalogue research): flight, the direct-hit damage
row's values and the impact / expiry explosions (catalogue name, radii, shrapnel, damage). Keyed by the output's
projectile type (domains/attack_outputs.lua outputs[].currentDefault). Nothing is read from the game: these are the
vanilla values; hd2.inspect reads the live ones.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
from reference_format import lua  # noqa: E402
from lua_offline import execute  # noqa: E402

RESEARCH = ROOT / 'research/projectile-stats-F5FEE03DCFDB.json'
OUTPUT = 'domains/projectile_stats.lua'


def output_types() -> dict:
    """{output id: projectile type} of every projectile-family attack output (the runtime catalogue)."""
    source = ('local catalog=(function()\n%s\nend)()\nlocal json=(function()\n%s\nend)()\n' % (
        (ROOT / 'domains/attack_outputs.lua').read_text(encoding='utf-8'),
        (ROOT / 'primary_mapper/json.lua').read_text(encoding='utf-8')))
    source += r'''
local out={}
for id,o in pairs(catalog.outputs)do
 if o.family=='projectile'and type(o.currentDefault)=='number'then out[id]=o.currentDefault end
end
return json.encode(out)'''
    return json.loads(execute(source.encode()))


def explosion(item):
    if not item:
        return None
    return {key: item[key] for key in ('name', 'label', 'inner_radius', 'outer_radius', 'shockwave_radius',
        'shrapnel_count', 'arc', 'damage')}


def build() -> dict:
    research = json.loads(RESEARCH.read_text(encoding='utf-8'))
    if research['writes'] or research['protectionChanges']:
        raise ValueError('the projectile stats research must be read-only')
    outputs = output_types()
    types = {}
    for output, kind in sorted(outputs.items()):
        row = research['rows'].get(str(kind))
        if not row:
            raise ValueError(f'{output}: projectile type {kind} has no researched row')
        types[kind] = {'flight': row['flight'], 'direct_damage': row['directDamage'],
            'impact': explosion(row['impact']), 'expiry': explosion(row['expiry'])}
    return {'source': {'research': 'projectile-stats-F5FEE03DCFDB.json', 'build': research['build'],
        'values': 'vanilla (the game data); hd2.inspect reads live values'}, 'outputs': len(outputs), 'types': types}


def outputs():
    return {OUTPUT: '-- Generated by scripts/generate_projectile_stats.py; do not edit.\nreturn ' + lua(build()) + '\n'}


def generate(check=False):
    stale = []
    for name, body in outputs().items():
        path = ROOT / name
        if not path.exists() or path.read_text(encoding='utf-8') != body:
            stale.append(name)
            if not check:
                path.write_text(body, encoding='utf-8', newline='\n')
    if check and stale:
        raise RuntimeError('Stale generated projectile stats domain: ' + ', '.join(stale))
    return stale


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    print(', '.join(generate(parser.parse_args().check)) or 'up to date')
